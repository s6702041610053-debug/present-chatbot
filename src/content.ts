export const questions: Question[] = (() => {
  const list: Question[] = []
  let id = 1
  for (const ch of chapters) {
    for (let k = 0; k < ch.questions; k++) {
      list.push({
        id,
        kind: 'in',
        chapter: ch.n,
        text: questionTexts[id - 1] ?? '',
        expected: `ตอบจากเนื้อหาบทที่ ${ch.n}`,
      })
      id++
    }
  }
  for (const g of outOfScope) {
    for (let k = 0; k < g.n; k++) {
      list.push({
        id,
        kind: g.key as Question['kind'],
        text: questionTexts[id - 1] ?? '',
        expected: 'แจ้งว่าไม่พบข้อมูลในตำรา',
      })
      id++
    }
  }
  return list
})()

